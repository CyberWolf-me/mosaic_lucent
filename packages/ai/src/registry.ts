import * as z from "zod/v4";
import { AI_OPERATION_NAMES, listRepresentations, representationCatalogPrompt } from "@lucent/core";
import visualAgentFile from "./prompts/visual-agent.json" with { type: "json" };
import boardHistorianFile from "./prompts/board-historian.json" with { type: "json" };
import externalSelectorFile from "./prompts/external-selector.json" with { type: "json" };
import meetingNotesFile from "./prompts/meeting-notes.json" with { type: "json" };
import stickyThemesFile from "./prompts/sticky-themes.json" with { type: "json" };
import vectorEditorFile from "./prompts/vector-editor.json" with { type: "json" };

/**
 * The prompt registry (M5). Prompts are data, not string literals in code.
 *
 * Two things drove this. The first is reviewability: the harness text is the
 * asset, and while it lived inside a template literal a change to it arrived in
 * a diff full of TypeScript, next to unrelated code changes, with nothing
 * recording that the *behaviour* being changed was the model's. A prompt now
 * changes by editing `prompts/<id>.json` and bumping its `version`, which is a
 * diff a reviewer can read as a change to what the model is told.
 *
 * The second is the trust boundary. The set of operations a prompt may produce
 * used to be interpolated from `AI_OPERATION_NAMES` at the point of use, so
 * "what may this prompt do" was a property of whichever code path built the
 * string. It is now a declared property of the registry entry, resolved once at
 * module load, and `buildUserPrompt` never sees it — which is what makes the
 * invariant "untrusted content cannot widen the vocabulary" checkable rather
 * than merely intended: content reaches the prompt through the envelopes in
 * prompt.ts, the vocabulary reaches it from here, and the two never meet.
 *
 * Narrowing, never widening. `vocabulary.base` names core's AI-permitted set,
 * and `only`/`without` may cut it down; there is no syntax for adding a name.
 * A prompt file therefore cannot advertise an operation the tool schema does not
 * accept, which is the drift that made hand-listing the operations in prose a
 * bug in the first place (see operations.ts's note on the single source of
 * truth).
 *
 * Why the files sit under `src/prompts/` rather than the package root: they are
 * imported statically, not read from disk. @lucent/ai is imported by the browser
 * bundle (packages/web/src/api.ts) as well as by the server, so a loader calling
 * `node:fs` at module load would break the web build's module graph; and
 * `tsconfig.json` pins `rootDir` to `src`, so a JSON outside it cannot be part
 * of the program. A static import satisfies both, and `tsc` copies the JSON into
 * `dist/prompts/` so the production image needs no extra file to be shipped.
 *
 * Generated sections (V4). The diagram families are the same kind of fact as the
 * vocabulary: core's representation registry already holds each family's
 * summary and construction rules, and a hand-written copy in the prompt is a
 * second list that drifts the first time a family is added. So a prompt may
 * name them by placeholder too, and they are resolved the same way — once, here,
 * at module load, into the SYSTEM prompt. Never per request: the user turn's
 * <board-context> is data, and a catalog living there would teach the model
 * that board data can carry instructions.
 */

/**
 * `base` has one legal value on purpose. It is written in the data so a reader
 * of the file can see where the vocabulary comes from without reading this
 * module, while the actual list stays derived from core's union at load time —
 * a name is never spelled out in prompt data, so a new operation in core reaches
 * every prompt without a second list to update.
 */
const vocabularySchema = z.object({
  base: z.literal("ai-permitted"),
  /**
   * Keep only these, in core's declaration order. An EMPTY list is legal and
   * means the prompt produces no operations at all — the Stage C1 historian is
   * read-only and declares that as data ("only: []") rather than by convention.
   * `only` with names still narrows as before; the never-wider invariant is
   * unchanged because an empty intersection is the narrowest vocabulary there is.
   */
  only: z.array(z.string().min(1)).optional(),
  /** Drop these. */
  without: z.array(z.string().min(1)).optional(),
});

const promptFileSchema = z.object({
  /** Stable, url-ish, and the key callers use. Renaming one is a new prompt. */
  id: z.string().regex(/^[a-z][a-z0-9-]*$/),
  /**
   * Bumped by hand when the text changes. It is part of the cache key
   * (cache.ts), so a prompt edit that forgets the bump would serve answers
   * generated by the old text — which is why the rendered body is hashed there
   * too, and the version is what a human reads in a log line.
   */
  version: z.number().int().positive(),
  description: z.string().min(1),
  vocabulary: vocabularySchema,
  /**
   * The prompt text, one array element per line, joined with "\n". A single
   * JSON string would carry the whole prompt as one `\n`-escaped blob, and the
   * point of moving prompts into data is that a wording change shows up as a
   * one-line diff.
   */
  body: z.array(z.string()).min(1),
});

type PromptFile = z.infer<typeof promptFileSchema>;

/** Where the resolved vocabulary is substituted into the body. */
const OPERATIONS_PLACEHOLDER = "{{operations}}";

/** Anything that looks like a placeholder, so a typo cannot ship silently. */
const ANY_PLACEHOLDER = /\{\{[^}\n]{1,40}\}\}/;

/** The families the model is told about at all, in registry order. */
const CREATABLE = listRepresentations().filter((r) => r.aiCreatable);

/**
 * Optional placeholders, each generated from core's representation registry.
 * Unlike `{{operations}}` none is mandatory — the historian or the sticky
 * sorter has no use for a diagram menu — but every one is fixed at load, so
 * the rendered text a cache key hashes (cache.ts) is still one string per
 * prompt version.
 *
 * - `{{families}}`: every creatable family's `- kind — summary` line with its
 *   construction rules beneath (core's `representationCatalogPrompt`).
 * - `{{region-kinds}}` / `{{whole-board-kinds}}`: which families may be a
 *   REGION on a board of another kind, and which draw only as a whole board.
 *   Generated for the same reason as the catalog: the region rule is a
 *   registry flag (`regionable`), and a hand-kept list in prose is the one
 *   that silently omits the next family added.
 */
const GENERATED_PLACEHOLDERS: Readonly<Record<string, string>> = Object.freeze({
  "{{families}}": representationCatalogPrompt(),
  "{{region-kinds}}": CREATABLE.filter((r) => r.regionable)
    .map((r) => r.kind)
    .join(", "),
  "{{whole-board-kinds}}": CREATABLE.filter((r) => !r.regionable)
    .map((r) => r.kind)
    .join(", "),
});

/** Every placeholder `render` resolves, as one alternation. */
const KNOWN_PLACEHOLDER = new RegExp(
  [OPERATIONS_PLACEHOLDER, ...Object.keys(GENERATED_PLACEHOLDERS)]
    .map((p) => p.replace(/[{}]/g, "\\$&"))
    .join("|"),
  "g",
);

/** A prompt as callers consume it: text already rendered, vocabulary resolved. */
export interface PromptEntry {
  readonly id: string;
  readonly version: number;
  readonly description: string;
  /**
   * Exactly what this prompt may emit, in core's declaration order. Callers that
   * filter or audit model output should read it from here rather than from
   * `AI_OPERATION_NAMES`, so a narrowed prompt is enforced and not just
   * advertised.
   */
  readonly vocabulary: readonly string[];
  /** The rendered system prompt, byte-identical to what the model receives. */
  readonly systemPrompt: string;
}

function resolveVocabulary(file: PromptFile): readonly string[] {
  const base = AI_OPERATION_NAMES;
  const named = [...(file.vocabulary.only ?? []), ...(file.vocabulary.without ?? [])];
  // A name that is not in the base set is either a typo or an attempt to add an
  // operation. Both fail here: silently ignoring an unknown `without` entry
  // would leave a prompt advertising an operation someone believed they had
  // removed, and an unknown `only` entry would quietly shrink the vocabulary.
  const unknown = named.filter((name) => !base.includes(name));
  if (unknown.length) {
    throw new Error(
      `prompt "${file.id}": vocabulary names ${unknown.join(", ")} are not in the AI-permitted operation set`,
    );
  }
  const only = file.vocabulary.only;
  const without = file.vocabulary.without;
  // `only: []` is the deliberate zero-operation vocabulary (the historian). It
  // is distinguished from a filter that *accidentally* drained the set: an
  // empty `only` array is present on purpose, whereas `without: [everything]`
  // or a typo'd `only` means someone believed the prompt could do something
  // it cannot. Only the accident throws.
  if (only !== undefined && only.length === 0) {
    return Object.freeze([]);
  }
  const names = base
    .filter((name) => (only ? only.includes(name) : true))
    .filter((name) => !without?.includes(name));
  if (!names.length) {
    throw new Error(`prompt "${file.id}": vocabulary resolved to nothing`);
  }
  return Object.freeze(names);
}

function render(file: PromptFile, vocabulary: readonly string[]): string {
  const body = file.body.join("\n");
  // A prompt that never names its vocabulary is the failure this registry
  // exists to prevent: the tool schema would accept operations the prose never
  // mentioned, or mention ones it no longer accepts.
  if (!body.includes(OPERATIONS_PLACEHOLDER)) {
    throw new Error(`prompt "${file.id}": body never uses ${OPERATIONS_PLACEHOLDER}`);
  }
  const values: Record<string, string> = {
    ...GENERATED_PLACEHOLDERS,
    [OPERATIONS_PLACEHOLDER]: vocabulary.length
      ? vocabulary.join(", ")
      : "(none — this prompt emits no operations)",
  };
  // One pass over the body, so substituted text is never itself scanned for
  // placeholders to substitute: the catalog is inserted, not re-interpreted.
  // The leftover check below still reads the whole rendered text, generated
  // sections included — a registry string that looked like a placeholder
  // would reach the model as a literal `{{…}}`, and that should fail here too.
  const rendered = body.replace(KNOWN_PLACEHOLDER, (placeholder) => values[placeholder]!);
  const leftover = ANY_PLACEHOLDER.exec(rendered);
  if (leftover) {
    throw new Error(`prompt "${file.id}": unresolved placeholder ${leftover[0]}`);
  }
  return rendered;
}

/**
 * Validate and render one prompt file. Exported for the tests, which build
 * hostile and narrowed files to prove the load-time rules actually reject —
 * a rule only the shipped file exercises is a rule nobody has tested.
 */
export function loadPromptFile(raw: unknown): PromptEntry {
  const parsed = promptFileSchema.safeParse(raw);
  if (!parsed.success) {
    throw new Error(`invalid prompt file: ${z.prettifyError(parsed.error)}`);
  }
  const file = parsed.data;
  const vocabulary = resolveVocabulary(file);
  return Object.freeze({
    id: file.id,
    version: file.version,
    description: file.description,
    vocabulary,
    systemPrompt: render(file, vocabulary),
  });
}

/**
 * Every prompt, keyed by id. Built at module load: an invalid prompt file is an
 * import-time throw, not a request-time 500 on whichever code path happened to
 * ask for it first.
 */
const REGISTRY = Object.freeze({
  "visual-agent": loadPromptFile(visualAgentFile),
  "board-historian": loadPromptFile(boardHistorianFile),
  "external-selector": loadPromptFile(externalSelectorFile),
  "meeting-notes": loadPromptFile(meetingNotesFile),
  "sticky-themes": loadPromptFile(stickyThemesFile),
  "vector-editor": loadPromptFile(vectorEditorFile),
});

/** The ids callers may ask for, checked by the compiler. */
export type PromptId = keyof typeof REGISTRY;

export function getPrompt(id: PromptId): PromptEntry {
  return REGISTRY[id];
}

export function listPrompts(): readonly PromptEntry[] {
  return Object.freeze(Object.values(REGISTRY));
}
