import type { GenerateRequest, GenerateResult } from "./provider.js";

/**
 * Response cache for the AI harness (M5).
 *
 * WHY A CACHE, GIVEN NON-DETERMINISM. Real providers sample: the same prompt
 * can answer differently twice. That is exactly why the cache is keyed on the
 * prompt's identity (id + version + a hash of the rendered text) and the full
 * request, and why it is opt-in per call site — a deployment that wants raw
 * sampling never touches it. What it buys, when on: identical re-asks (a
 * client retry after a dropped socket, a demo replaying the same ask, the
 * eval runner running the same golden set twice) cost zero tokens, and a
 * prompt bump (`registry.ts` versions) can never serve an answer generated by
 * the old text, because the version and the text hash are both in the key.
 *
 * THE KEY IS CANONICAL. A stable stringify (sorted object keys, arrays in
 * order) feeds the hash, so two structurally equal requests hash equal even
 * when the JSON was built in a different key order. Requests carrying images
 * or documents are not cacheable: their bytes do not belong in a cache key,
 * and hash-truncating them would collide two different attachments.
 */

/** What a cache entry holds: the provider's answer, plus who answered. */
export interface CacheEntry {
  result: GenerateResult;
  /** Epoch ms when the entry was written; the TTL is measured from here. */
  storedAt: number;
}

export interface CacheKeyInput {
  /** Provider name (`MockProvider`, `AnthropicProvider`, …) — part of the key. */
  providerName: string;
  /** Prompt identity (prompt.ts). A version bump invalidates everything prior. */
  promptId: string;
  promptVersion: number;
  /** Hash of the rendered system prompt text, so a hand-edit still busts the cache. */
  promptHash: string;
  request: GenerateRequest;
}

/** Requests with attachments are never cached; `null` means "do not cache". */
export async function cacheKeyFor(input: CacheKeyInput): Promise<string | null> {
  if ((input.request.images?.length ?? 0) > 0) return null;
  if ((input.request.documents?.length ?? 0) > 0) return null;
  const canonical = stableStringify({
    providerName: input.providerName,
    promptId: input.promptId,
    promptVersion: input.promptVersion,
    promptHash: input.promptHash,
    message: input.request.message,
    summary: input.request.summary,
    history: input.request.history ?? [],
  });
  // crypto.subtle is the one hash interface that exists in Node 18+, browsers
  // and workers alike, which keeps this module importable everywhere the
  // harness goes. The await is the price of that portability.
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(canonical));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/**
 * JSON.stringify with object keys sorted, recursively. Arrays keep their order
 * (a summary's node order is meaning, not accident). Returns the exact bytes
 * hashed, so the key's preimage is always reconstructible for debugging.
 */
export function stableStringify(value: unknown): string {
  if (value === null || typeof value !== "object") return JSON.stringify(value) ?? "null";
  if (Array.isArray(value)) return `[${value.map((v) => stableStringify(v)).join(",")}]`;
  const entries = Object.entries(value as Record<string, unknown>)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${stableStringify(v)}`).join(",")}}`;
}

export interface ResponseCacheOptions {
  /** Entries older than this are answers, not cache. Default 1 hour. */
  ttlMs?: number;
  /** LRU bound. Default 256. */
  maxEntries?: number;
  /** Injected clock, so TTL behaviour is testable. */
  now?: () => number;
}

export interface CacheStats {
  hits: number;
  misses: number;
  puts: number;
  evictions: number;
  expired: number;
}

/**
 * Process-local LRU with TTL. The default is correct for one instance; a
 * multi-instance deployment shares answers through its stores, not through a
 * per-process cache, and that is fine — a miss costs one provider call, which
 * is exactly what the un-cached world costs every time.
 */
export class ResponseCache {
  private readonly entries = new Map<string, CacheEntry>();
  private readonly ttlMs: number;
  private readonly maxEntries: number;
  private readonly clock: () => number;
  readonly stats: CacheStats = { hits: 0, misses: 0, puts: 0, evictions: 0, expired: 0 };

  constructor(options: ResponseCacheOptions = {}) {
    this.ttlMs = options.ttlMs ?? 60 * 60_000;
    this.maxEntries = options.maxEntries ?? 256;
    this.clock = options.now ?? Date.now;
  }

  /** A hit refreshes recency; a stale entry is a miss that drops the row. */
  get(key: string): CacheEntry | undefined {
    const entry = this.entries.get(key);
    if (!entry) {
      this.stats.misses += 1;
      return undefined;
    }
    if (this.clock() - entry.storedAt >= this.ttlMs) {
      this.entries.delete(key);
      this.stats.expired += 1;
      this.stats.misses += 1;
      return undefined;
    }
    // Recency: delete + re-insert moves the key to the LRU's back.
    this.entries.delete(key);
    this.entries.set(key, entry);
    this.stats.hits += 1;
    return entry;
  }

  put(key: string, result: GenerateResult): void {
    this.stats.puts += 1;
    this.entries.set(key, { result, storedAt: this.clock() });
    while (this.entries.size > this.maxEntries) {
      const oldest = this.entries.keys().next();
      if (oldest.done) break;
      this.entries.delete(oldest.value);
      this.stats.evictions += 1;
    }
  }

  /** Test seam and shutdown helper; returns how many rows went away. */
  clear(): number {
    const n = this.entries.size;
    this.entries.clear();
    return n;
  }

  get size(): number {
    return this.entries.size;
  }
}
