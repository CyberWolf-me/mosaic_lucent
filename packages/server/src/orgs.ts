import { randomBytes } from "node:crypto";
import { and, desc, eq, lt, lte, or } from "drizzle-orm";
import { auditLog, memberships, organizations, users } from "./db/schema.js";
import type { Db } from "./db/client.js";
import type { DbAuditEntry } from "./db/schema.js";

/**
 * Org store (M2).
 *
 * The org table already existed (the membership FK needed it), but no
 * request path ever read from it. This module gives the rest of the
 * server a typed interface for the membership lifecycle: create, rename,
 * delete, list members, change role, remove member, list the orgs a user
 * is in. The role hierarchy is documented in `identity.ts` (viewer / editor
 * / owner), where `roleAtLeast` is the only comparison helper.
 *
 * Storage is an interface so the in-memory implementation here can be
 * swapped for Postgres in production without touching handlers.
 */

export interface StoredOrg {
  id: string;
  name: string;
  createdAt: number;
}

export interface StoredMembership {
  userId: string;
  orgId: string;
  role: "owner" | "editor" | "viewer";
}

/**
 * Audit-friendly log entry written from every mutating route (M2.6).
 * Kept in this module because orgs are the place audit metadata first
 * lands at — every org-scoped mutation carries an orgId.
 *
 * WRITE SHAPE → `audit_log` COLUMNS (the table lives in db/schema.ts). The
 * type is a strict superset of what the pre-M2.6 callers passed, so app.ts's
 * existing `org.create` / `org.rename` / `org.delete` / `board.delete` call
 * sites keep compiling and behaving unchanged, while the mutating routes still
 * to be wired can fill in the richer columns the table already has:
 *
 *   id?         → id           generated (`aud_…`) when omitted; never reused
 *   orgId       → org_id       NOT NULL. Account-level actions have no org of
 *                              their own and must pass `personalOrgId(userId)`
 *   actorId     → actor_id     nullable: cron/webhook/system actions have no
 *                              user behind them
 *   actorEmail? → actor_email  denormalised on purpose: the row must stay
 *                              readable after the actor deletes their account
 *   action      → action       dotted name, e.g. `board.member.role_changed`
 *   subject?    → target_id    LEGACY field, still accepted. `targetId` wins
 *                              when both are given; otherwise `subject` IS the
 *                              target id. An empty subject means "no target"
 *   targetType? → target_type  defaults to the action's first dotted segment
 *                              (`org.rename` → `org`), so rows written by
 *                              legacy `subject` callers are still reachable
 *                              through `audit_log_target_idx`
 *   targetId?   → target_id    what new callers should send instead of subject
 *   ip          → ip           required: an audit row with no source address is
 *                              half a row. Pass null explicitly if unknown
 *   userAgent?  → user_agent
 *   metadata?   → metadata     JSONB; defaults to `{}`
 *   at          → at           ms since epoch
 *
 * `normalizeAuditEntry` is the only place that mapping happens and both stores
 * call it. That is deliberate: M2.6 shipped a Postgres `audit()` that was a
 * no-op while the in-memory one recorded correctly, so every test passed and
 * production wrote nothing. Shared normalisation means the two stores can now
 * differ in storage but never in shape.
 */
export interface AuditEntry {
  /** Row id. Generated by the store when omitted. */
  id?: string;
  orgId: string;
  /** null for actions no user initiated (migration, cron, webhook). */
  actorId: string | null;
  actorEmail?: string | null;
  action: string;
  /** Free-form subject id (board id, membership id, …). Maps to `target_id`. */
  subject?: string;
  targetType?: string | null;
  targetId?: string | null;
  ip: string | null;
  userAgent?: string | null;
  metadata?: Record<string, unknown>;
  at: number;
}

/**
 * What a read returns: every column present, nothing optional, and `subject`
 * mirrored from `target_id` so pre-M2.6 readers keep working. It is assignable
 * to `AuditEntry`, and `normalizeAuditEntry` is idempotent over it, so a row
 * read out of one store can be written verbatim into the other — the property
 * test/audit-store.test.ts leans on to assert the two are interchangeable.
 */
export interface StoredAuditEntry extends AuditEntry {
  id: string;
  actorEmail: string | null;
  /** Always `targetId ?? ""`; kept so the legacy field round-trips. */
  subject: string;
  targetType: string | null;
  targetId: string | null;
  userAgent: string | null;
  metadata: Record<string, unknown>;
}

/**
 * Keyset cursor for `auditFor`: the last row of the previous page. `at` alone
 * is not unique — one request can write several entries in the same
 * millisecond — so the id breaks the tie and the page boundary neither repeats
 * nor skips a row.
 */
export interface AuditCursor {
  at: number;
  id: string;
}

export interface OrgStore {
  // Orgs
  insert(org: StoredOrg): Promise<void>;
  get(orgId: string): Promise<StoredOrg | undefined>;
  /** Personal-org id for a user, created lazily on first need. */
  ensurePersonal(userId: string, displayName: string, now: number): Promise<StoredOrg>;
  rename(orgId: string, name: string): Promise<void>;
  /** Hard delete. Refuses if any non-personal board is in the org. */
  delete(orgId: string): Promise<void>;
  /** All orgs the user is a member of, with their role on each. */
  listForUser(userId: string): Promise<Array<{ org: StoredOrg; role: StoredMembership["role"] }>>;

  // Memberships
  membershipsFor(userId: string): Promise<StoredMembership[]>;
  /** Insert or update. Use `upsertMembership` so the join table stays consistent. */
  setMembership(membership: StoredMembership): Promise<void>;
  removeMembership(orgId: string, userId: string): Promise<void>;
  /** Members on a board, with user metadata if `withUsers` is true. */
  membersOf(orgId: string): Promise<Array<StoredMembership & { email: string; name: string }>>;

  // Audit log. Append-only: there is deliberately no update and no delete
  // counterpart. Rows leave this table exactly one way, with the org they
  // belong to, through `audit_log.org_id`'s ON DELETE CASCADE.
  audit(entry: AuditEntry): Promise<void>;
  /**
   * One page of an org's audit entries, newest first. `limit` is clamped to
   * `AUDIT_PAGE_MAX`; to continue, pass the last row of the previous page as
   * `cursor` (`{ at, id }`).
   */
  auditFor(orgId: string, limit: number, cursor?: AuditCursor): Promise<StoredAuditEntry[]>;
}

/** Personal-org id is deterministic from the user id so migrations are stable. */
export function personalOrgId(userId: string): string {
  return `org_personal_${userId}`;
}

/** Generate a fresh non-personal org id. */
export function newOrgId(): string {
  return `org_${Date.now().toString(36)}${randomBytes(3).toString("hex")}`;
}

/**
 * Fresh audit-row id, built the way every other id in this codebase is
 * (`newOrgId` above, `tok_`/`evt_`/`rst_` in tokens.ts): a base36 millisecond
 * so ids sort roughly by time, plus random bytes so two entries written in the
 * same millisecond cannot collide on the primary key.
 */
export function newAuditId(): string {
  return `aud_${Date.now().toString(36)}${randomBytes(3).toString("hex")}`;
}

/**
 * Hard ceiling on one page of audit history. The console asks for 100
 * (`auditFor(orgId, 100)` in app.ts); the cap is what keeps a future `?limit=100000` from turning an
 * Enterprise tenant's trail into a full table scan and a huge JSON response.
 */
export const AUDIT_PAGE_MAX = 200;

/**
 * Clamp a requested page size to [0, AUDIT_PAGE_MAX]. A non-positive or
 * non-finite limit reads nothing, and both stores return early on 0 rather
 * than emitting `LIMIT 0` — the intent is clearer and it costs no round trip.
 */
export function clampAuditLimit(limit: number): number {
  if (!Number.isFinite(limit)) return 0;
  return Math.min(Math.max(Math.floor(limit), 0), AUDIT_PAGE_MAX);
}

/**
 * The single place a write shape becomes a row, shared by both stores.
 *
 *  - `targetId` wins over the legacy `subject`; whichever survives becomes
 *    `target_id`, and `subject` is echoed back on read so old readers work.
 *  - An empty `subject` counts as absence, not as an id: `""` is what a
 *    targetless row mirrors back, and treating it as a target would make a
 *    re-write of a row that was just read store something different.
 *  - `targetType` defaults to the action's first dotted segment
 *    (`org.rename` → `org`). Without it, rows from legacy `subject` callers
 *    would carry a NULL leading column and could never be found through
 *    `audit_log_target_idx (target_type, target_id)`.
 */
export function normalizeAuditEntry(entry: AuditEntry): StoredAuditEntry {
  const target = entry.targetId ?? entry.subject ?? "";
  const targetId = target.length > 0 ? target : null;
  const targetType =
    entry.targetType ?? (targetId === null ? null : (entry.action.split(".")[0] ?? null));
  return {
    id: entry.id ?? newAuditId(),
    orgId: entry.orgId,
    actorId: entry.actorId,
    actorEmail: entry.actorEmail ?? null,
    action: entry.action,
    subject: targetId ?? "",
    targetType,
    targetId,
    ip: entry.ip,
    userAgent: entry.userAgent ?? null,
    metadata: normalizeMetadata(entry.metadata),
    at: entry.at,
  };
}

/**
 * JSONB round-trip semantics, applied on the way in for both stores: the column
 * stores JSON, so an `undefined` member disappears and a Date comes back as a
 * string. Doing it here means an in-memory test sees exactly what Postgres
 * would hand back, instead of the richer JS object it was handed — that class
 * of quiet difference is how the M2.6 stub survived a green suite.
 */
function normalizeMetadata(metadata: Record<string, unknown> | undefined): Record<string, unknown> {
  if (metadata === undefined) return {};
  return JSON.parse(JSON.stringify(metadata)) as Record<string, unknown>;
}

/**
 * Total order for the trail: newest first, and inside one millisecond the
 * higher id first. The tiebreak is not cosmetic — it is what makes keyset
 * pagination exact when a single request writes several entries at the same
 * `at`. Mirrors `ORDER BY at DESC, id DESC` in the SQL store.
 */
function compareAuditDesc(a: StoredAuditEntry, b: StoredAuditEntry): number {
  if (a.at !== b.at) return b.at - a.at;
  if (a.id === b.id) return 0;
  return a.id < b.id ? 1 : -1;
}

/** Strictly past the cursor in `(at DESC, id DESC)` order. */
function afterCursor(entry: StoredAuditEntry, cursor: AuditCursor): boolean {
  return entry.at < cursor.at || (entry.at === cursor.at && entry.id < cursor.id);
}

/**
 * An audit write must not turn a mutation that already succeeded into a 500,
 * and must not fail silently either. The one expected loss is an entry for an
 * org row that is already gone — `audit_log.org_id` is a cascading FK, and
 * `DELETE /api/orgs/:id` (app.ts) deletes the org and *then* audits
 * `org.delete`, so that entry has nowhere to land. Log it and continue;
 * every other failure propagates.
 */
function warnAuditDropped(row: StoredAuditEntry): void {
  console.warn(
    `[lucent] audit entry dropped: org ${row.orgId} no longer exists (action=${row.action}, actor=${row.actorId ?? "system"})`,
  );
}

export class InMemoryOrgStore implements OrgStore {
  private readonly orgs = new Map<string, StoredOrg>();
  private readonly memberships: StoredMembership[] = [];
  private readonly auditEntries: StoredAuditEntry[] = [];
  /**
   * Optional hook so `membersOf` can join names + emails. The Postgres
   * implementation joins the `users` table directly; the in-memory store
   * has no shared map, so a caller that needs the joined shape wires this
   * in (e.g. `app.ts` passes a `userStore.findById`-shaped function).
   */
  userFinder?: (userId: string) => Promise<{ email: string; name: string } | undefined>;
  /**
   * Org ids this store has deleted. `audit_log.org_id` is ON DELETE CASCADE, so
   * in Postgres an entry written after its org is gone is refused by the FK; a
   * plain array would keep it, and the two stores would then disagree about
   * exactly the sequence `DELETE /api/orgs/:id` performs. The tombstone
   * reproduces the FK for the lifecycle this store can actually see. Ids it has
   * never held are still accepted: personal orgs are created through the
   * UserStore, not here, and dropping their entries would be a divergence in
   * the other direction.
   */
  private readonly deletedOrgs = new Set<string>();

  async insert(org: StoredOrg): Promise<void> {
    this.orgs.set(org.id, org);
    // The row exists again, so the FK would accept writes again.
    this.deletedOrgs.delete(org.id);
  }

  async get(orgId: string): Promise<StoredOrg | undefined> {
    return this.orgs.get(orgId);
  }

  async ensurePersonal(userId: string, displayName: string, now: number): Promise<StoredOrg> {
    const id = personalOrgId(userId);
    const existing = this.orgs.get(id);
    if (existing) return existing;
    const org: StoredOrg = {
      id,
      name: `${displayName.trim() || "User"}'s workspace`,
      createdAt: now,
    };
    this.orgs.set(id, org);
    this.deletedOrgs.delete(id);
    if (!this.memberships.some((m) => m.userId === userId && m.orgId === id)) {
      this.memberships.push({ userId, orgId: id, role: "owner" });
    }
    return org;
  }

  async rename(orgId: string, name: string): Promise<void> {
    const org = this.orgs.get(orgId);
    if (!org) return;
    this.orgs.set(orgId, { ...org, name });
  }

  async delete(orgId: string): Promise<void> {
    this.orgs.delete(orgId);
    for (let i = this.memberships.length - 1; i >= 0; i -= 1) {
      if (this.memberships[i]!.orgId === orgId) this.memberships.splice(i, 1);
    }
    // `audit_log.org_id` cascades in Postgres (db/schema.ts): deleting an
    // org deletes its trail. Mirror it, or `auditFor` would answer differently
    // in the two stores after a delete.
    for (let i = this.auditEntries.length - 1; i >= 0; i -= 1) {
      if (this.auditEntries[i]!.orgId === orgId) this.auditEntries.splice(i, 1);
    }
    this.deletedOrgs.add(orgId);
  }

  async listForUser(
    userId: string,
  ): Promise<Array<{ org: StoredOrg; role: StoredMembership["role"] }>> {
    const out: Array<{ org: StoredOrg; role: StoredMembership["role"] }> = [];
    for (const m of this.memberships) {
      if (m.userId !== userId) continue;
      const org = this.orgs.get(m.orgId);
      if (!org) continue;
      out.push({ org, role: m.role });
    }
    return out.sort((a, b) => a.org.createdAt - b.org.createdAt);
  }

  async membershipsFor(userId: string): Promise<StoredMembership[]> {
    return this.memberships.filter((m) => m.userId === userId);
  }

  async setMembership(membership: StoredMembership): Promise<void> {
    const i = this.memberships.findIndex(
      (m) => m.userId === membership.userId && m.orgId === membership.orgId,
    );
    if (i === -1) this.memberships.push(membership);
    else this.memberships[i] = membership;
  }

  async removeMembership(orgId: string, userId: string): Promise<void> {
    for (let i = this.memberships.length - 1; i >= 0; i -= 1) {
      if (this.memberships[i]!.orgId === orgId && this.memberships[i]!.userId === userId) {
        this.memberships.splice(i, 1);
      }
    }
  }

  async membersOf(
    orgId: string,
  ): Promise<Array<StoredMembership & { email: string; name: string }>> {
    const out: Array<StoredMembership & { email: string; name: string }> = [];
    for (const m of this.memberships) {
      if (m.orgId !== orgId) continue;
      const user = this.userFinder ? await this.userFinder(m.userId) : undefined;
      out.push({ ...m, email: user?.email ?? "", name: user?.name ?? "(removed)" });
    }
    return out;
  }

  async audit(entry: AuditEntry): Promise<void> {
    const row = normalizeAuditEntry(entry);
    if (this.deletedOrgs.has(row.orgId)) {
      // The FK would reject this write in Postgres; see `deletedOrgs`.
      warnAuditDropped(row);
      return;
    }
    if (this.auditEntries.some((e) => e.id === row.id)) {
      // `audit_log.id` is the primary key. Append-only means a second write
      // under an existing id is an error, never an overwrite.
      throw new Error(`audit entry ${row.id} already exists`);
    }
    this.auditEntries.push(row);
  }

  /** Same order, same clamp, same cursor semantics as the SQL store. */
  async auditFor(orgId: string, limit: number, cursor?: AuditCursor): Promise<StoredAuditEntry[]> {
    const max = clampAuditLimit(limit);
    if (max === 0) return [];
    return (
      this.auditEntries
        .filter((e) => e.orgId === orgId && (cursor === undefined || afterCursor(e, cursor)))
        .sort(compareAuditDesc)
        .slice(0, max)
        // Detached copies: a caller mutating what it read must not be able to
        // rewrite history, which a row out of Postgres already guarantees.
        .map((e) => structuredClone(e))
    );
  }
}

export class PostgresOrgStore implements OrgStore {
  constructor(private readonly target: Db) {}

  async insert(org: StoredOrg): Promise<void> {
    await this.target.db.insert(organizations).values({
      id: org.id,
      name: org.name,
      createdAt: org.createdAt,
    });
  }

  async get(orgId: string): Promise<StoredOrg | undefined> {
    const rows = await this.target.db
      .select()
      .from(organizations)
      .where(eq(organizations.id, orgId))
      .limit(1);
    return rows[0];
  }

  async ensurePersonal(userId: string, displayName: string, now: number): Promise<StoredOrg> {
    const id = personalOrgId(userId);
    await this.target.db
      .insert(organizations)
      .values({ id, name: `${displayName.trim() || "User"}'s workspace`, createdAt: now })
      .onConflictDoNothing();
    await this.target.db
      .insert(memberships)
      .values({ userId, orgId: id, role: "owner" })
      .onConflictDoNothing();
    const rows = await this.target.db
      .select()
      .from(organizations)
      .where(eq(organizations.id, id))
      .limit(1);
    return rows[0]!;
  }

  async rename(orgId: string, name: string): Promise<void> {
    await this.target.db.update(organizations).set({ name }).where(eq(organizations.id, orgId));
  }

  async delete(orgId: string): Promise<void> {
    // Memberships cascade on the FK, so a single DELETE cleans both.
    await this.target.db.delete(organizations).where(eq(organizations.id, orgId));
  }

  async listForUser(
    userId: string,
  ): Promise<Array<{ org: StoredOrg; role: StoredMembership["role"] }>> {
    const rows = await this.target.db
      .select({ org: organizations, role: memberships.role })
      .from(memberships)
      .innerJoin(organizations, eq(organizations.id, memberships.orgId))
      .where(eq(memberships.userId, userId));
    return rows.map((r) => ({ org: r.org, role: r.role }));
  }

  async membershipsFor(userId: string): Promise<StoredMembership[]> {
    const rows = await this.target.db
      .select()
      .from(memberships)
      .where(eq(memberships.userId, userId));
    return rows.map((r) => ({ userId: r.userId, orgId: r.orgId, role: r.role }));
  }

  async setMembership(membership: StoredMembership): Promise<void> {
    await this.target.db
      .insert(memberships)
      .values({ userId: membership.userId, orgId: membership.orgId, role: membership.role })
      .onConflictDoUpdate({
        target: [memberships.userId, memberships.orgId],
        set: { role: membership.role },
      });
  }

  async removeMembership(orgId: string, userId: string): Promise<void> {
    await this.target.db
      .delete(memberships)
      .where(and(eq(memberships.orgId, orgId), eq(memberships.userId, userId)));
  }

  async membersOf(
    orgId: string,
  ): Promise<Array<StoredMembership & { email: string; name: string }>> {
    const rows = await this.target.db
      .select({ membership: memberships, user: users })
      .from(memberships)
      .innerJoin(users, eq(users.id, memberships.userId))
      .where(eq(memberships.orgId, orgId));
    return rows.map((r) => ({
      userId: r.membership.userId,
      orgId: r.membership.orgId,
      role: r.membership.role,
      email: r.user.email,
      name: r.user.name,
    }));
  }

  /**
   * Append-only insert. There is no update or delete counterpart by design: the
   * only way a row leaves `audit_log` is with its org, through the cascading FK
   * on `org_id`. Ids are generated in `normalizeAuditEntry`, so a caller that
   * supplies one twice gets a primary-key violation rather than an overwrite.
   */
  async audit(entry: AuditEntry): Promise<void> {
    const row = normalizeAuditEntry(entry);
    try {
      await this.target.db.insert(auditLog).values({
        id: row.id,
        orgId: row.orgId,
        actorId: row.actorId,
        actorEmail: row.actorEmail,
        action: row.action,
        targetType: row.targetType,
        targetId: row.targetId,
        metadata: row.metadata,
        ip: row.ip,
        userAgent: row.userAgent,
        at: row.at,
      });
    } catch (err) {
      // 23503 = foreign_key_violation: the org is already gone, so its trail
      // went with it and this entry has nowhere to land (see
      // `warnAuditDropped`). Every other error is a real failure and is
      // rethrown — a store that swallows write errors is how the M2.6 no-op
      // shipped in the first place.
      if (isForeignKeyViolation(err)) {
        warnAuditDropped(row);
        return;
      }
      throw err;
    }
  }

  /**
   * One page of an org's trail, newest first.
   *
   * INDEX USE. Both branches are served by `audit_log_org_at_idx (org_id, at)`:
   * `org_id` is an equality on the leading key and `at` is the second, so the
   * planner walks that index backwards — `ORDER BY at DESC` never sorts the
   * org's whole history, and `LIMIT` stops the walk at the page boundary. The `id DESC` tiebreak is settled by an Incremental Sort over
   * each equal-`at` group (`Presorted Key: at`), not by re-sorting the result.
   *
   * The paginated branch adds `at <= cursor.at`, which becomes the index range
   * bound that lets the walk *start* at the cursor instead of at the newest
   * row. The OR term cannot be a bound, but it only rechecks the rows sharing
   * the boundary millisecond, so it cannot cost more than that one group.
   * Keying on `(at, id)` rather than `at` alone is what makes the boundary
   * exact: several entries per millisecond is normal (one request, three
   * mutations), and an `at`-only cursor would repeat or skip them.
   *
   * Measured on 30k rows / 10k in the org, `EXPLAIN (ANALYZE, BUFFERS)` for a
   * 100-row page: `Index Scan Backward using audit_log_org_at_idx`, 9-10 shared
   * buffer hits, 102 rows touched, `Rows Removed by Filter: 1` for the OR
   * recheck. No seq scan and no full sort in either branch.
   *
   * The table's other two indexes are for reads this method does not perform:
   * `audit_log_actor_idx (actor_id)` for "everything this user did", and
   * `audit_log_target_idx (target_type, target_id)` for "everything that
   * happened to this board" — which is why `normalizeAuditEntry` fills
   * `target_type` in rather than leaving that index's leading column NULL.
   */
  async auditFor(orgId: string, limit: number, cursor?: AuditCursor): Promise<StoredAuditEntry[]> {
    const max = clampAuditLimit(limit);
    if (max === 0) return [];
    const rows = await this.target.db
      .select()
      .from(auditLog)
      .where(
        cursor === undefined
          ? eq(auditLog.orgId, orgId)
          : and(
              eq(auditLog.orgId, orgId),
              lte(auditLog.at, cursor.at),
              or(lt(auditLog.at, cursor.at), lt(auditLog.id, cursor.id)),
            ),
      )
      .orderBy(desc(auditLog.at), desc(auditLog.id))
      .limit(max);
    return rows.map((row) => toStoredAuditEntry(row));
  }
}

/** Row → read shape. Nullable columns stay null; `subject` mirrors `target_id`. */
function toStoredAuditEntry(row: DbAuditEntry): StoredAuditEntry {
  return {
    id: row.id,
    orgId: row.orgId,
    actorId: row.actorId,
    actorEmail: row.actorEmail,
    action: row.action,
    subject: row.targetId ?? "",
    targetType: row.targetType,
    targetId: row.targetId,
    ip: row.ip,
    userAgent: row.userAgent,
    metadata: (row.metadata ?? {}) as Record<string, unknown>,
    at: row.at,
  };
}

/** pg's `foreign_key_violation` (SQLSTATE 23503), however the driver wraps it. */
function isForeignKeyViolation(err: unknown): boolean {
  return typeof err === "object" && err !== null && (err as { code?: unknown }).code === "23503";
}
