import { createDb, closeDb } from "../src/db/client.js";
import { migrate } from "../src/db/migrate.js";
import { PostgresJobQueue } from "../src/jobs.js";
import { jobs } from "../src/db/schema.js";
import { sql } from "drizzle-orm";
const db = createDb(process.env.LUCENT_DATABASE_URL!);
await migrate(db);
await db.db.delete(jobs);
const q = new PostgresJobQueue(db);
await q.enqueue({ family: "ai", type: "generate" });
const raw = await db.db.execute(sql`select * from ${jobs}`);
console.log("RAW KEYS:", JSON.stringify(Object.keys((raw.rows[0] ?? {}) as object)));
console.log("RAW ROW:", JSON.stringify(raw.rows[0]));
const claimed = await q.claim(["ai"], "worker-1", 10);
console.log("CLAIMED:", JSON.stringify(claimed));
await db.db.delete(jobs);
await closeDb(db);
